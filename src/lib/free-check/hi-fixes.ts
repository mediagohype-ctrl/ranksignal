/** Fix ids the free check can never return, so they need no Hindi (AI answers are never asked; no PageSpeed test). */
export const HI_FIXES_NOT_NEEDED = [
  "seo-core_web_vitals",
  "geo-ai_mention_rate",
  "geo-ai_citation_rate",
  "geo-competitor_share",
  "brand-ai_recommendation",
  "brand-ai_knowledge",
] as const;

export interface FixText {
  title: string;
  whatsWrong: string;
  howToFix: string[];
  /** False when no Hindi exists for this fix and the English text is shown. */
  translated: boolean;
}

/** The fix text to show in Hindi: translated when we have it, the English original otherwise. */
export function hindiFix(issue: { id: string; title: string; whatsWrong: string; howToFix: string[]; affectedCount: number }): FixText {
  const hi = HI_FIXES[issue.id];
  if (!hi) return { title: issue.title, whatsWrong: issue.whatsWrong, howToFix: issue.howToFix, translated: false };
  return {
    title: hi.title(issue.affectedCount),
    whatsWrong: hi.what,
    // Never more steps than the English result carries for this fix.
    howToFix: hi.steps.slice(0, Math.max(1, issue.howToFix.length)),
    translated: true,
  };
}
