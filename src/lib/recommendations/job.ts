// "analyze" workflow (blueprint §2.2 steps 6–8): evidence → deterministic recommendations →
// optional LLM drafting of text (never classification) → policy engine → draft hash → routing.
import { Prisma } from "@prisma/client";
import { z } from "zod";
import { db } from "@/lib/db";
import type { JobHandler } from "@/lib/jobs/queue";
import { JobError, type ActionTarget, type ExtractedPage, type VisibilityMetrics } from "@/lib/types";
import { generateStructured, isLlmConfigured } from "@/lib/providers/llm";
import { reserveCredits, recordUsage, releaseReservation } from "@/lib/billing/usage";
import { POLICY_VERSION, detectRegulatedClaims, type PolicyResult } from "@/lib/policy/engine";
import { draftHash } from "@/lib/actions/hash";
import { capabilitiesOf, evaluatePolicy, type ProjectSettings } from "@/lib/actions/gate";
import { requestApproval, requestExecution } from "@/lib/actions/service";
import {
  buildRecommendations, clip, dedupeKey, scorePriority,
  type FindingEvidence, type PageEvidence, type PromptEvidence, type RecDraft,
} from "@/lib/recommendations/rules";

const OPEN_STATUSES = ["proposed", "awaiting_approval", "approved", "executing", "blocked", "rollback_pending"];
const WRITE_TYPES = new Set(["update_meta_description", "update_title", "add_faq_schema", "update_schema", "update_content", "update_excerpt"]);
const MAX_LLM_DRAFTS = 10;

const metaSchema = z.object({ metaDescription: z.string(), unsupportedClaims: z.array(z.string()) });
const briefSchema = z.object({ outline: z.array(z.string()), unsupportedClaims: z.array(z.string()) });

interface BusinessFacts {
  name: string;
  brands: string[];
  categories: string[];
  audience: string | null;
  facts: string[];
}

function factsBlock(f: BusinessFacts) {
  return [
    `Business: ${f.name}`,
    `Brand names: ${f.brands.join(", ") || f.name}`,
    f.categories.length ? `Categories: ${f.categories.join(", ")}` : "",
    f.audience ? `Audience: ${f.audience}` : "",
    f.facts.length ? `Approved facts:\n- ${f.facts.join("\n- ")}` : "Approved facts: (none provided beyond the above)",
  ].filter(Boolean).join("\n");
}

/** Result of an LLM drafting attempt: cost, whether AI text ended up in the draft, and how many claims it flagged. */
export interface LlmRefineResult {
  costMicros: number;
  wroteText: boolean;
  unsupportedClaims: number;
}

/**
 * AI-written text is never published without a human looking at it: any draft that contains LLM text, or for which
 * the LLM flagged unsupported claims, is forced from auto_execute to approval_required. Blocked stays blocked.
 */
export function enforceLlmReview(policy: PolicyResult, o: { llmWritten: boolean; unsupportedClaims: number }): PolicyResult {
  if (policy.decision !== "auto_execute" || (!o.llmWritten && o.unsupportedClaims === 0)) return policy;
  const why = o.unsupportedClaims > 0 ? "AI flagged possibly unsupported claims" : "draft text was written by AI";
  return { ...policy, decision: "approval_required", reason: `${policy.reason} (review required: ${why})` };
}

async function llmRefine(d: RecDraft, facts: BusinessFacts): Promise<LlmRefineResult | null> {
  if (!d.llmDraft || !d.proposedChange) return null;
  const system = [
    "You draft copy for human review on a website-optimization platform.",
    "Use ONLY the approved business facts below and facts visibly present in the supplied page evidence.",
    "Never invent prices, statistics, awards, guarantees, rankings, or medical/legal/financial claims.",
    "List any statement you could not support from the approved facts in unsupportedClaims.",
    "APPROVED BUSINESS FACTS (trusted):",
    factsBlock(facts),
  ].join("\n");
  if (d.llmDraft.kind === "meta_description") {
    const p = d.llmDraft.page;
    const user = [
      `Task: write one meta description (120–155 characters) for the page below.`,
      `URL: ${p?.url ?? d.target.url ?? ""}`,
      `Title: ${p?.title ?? ""}`,
      `H1: ${(p?.h1 ?? []).join(" / ")}`,
      `Page text sample:\n${(p?.textSample ?? "").slice(0, 1500)}`,
    ].join("\n");
    const res = await generateStructured({ schema: metaSchema, system, user, maxTokens: 300 });
    if (!res) return null;
    const text = clip(res.data.metaDescription, 160);
    const wroteText = text.length >= 50;
    if (wroteText) {
      d.proposedChange = { ...d.proposedChange, after: text };
      d.rationale += " Draft text generated by AI from approved facts and page evidence — review before approving.";
      if (res.data.unsupportedClaims.length) {
        d.rationale += ` AI flagged possibly unsupported claims: ${res.data.unsupportedClaims.slice(0, 3).join("; ")}.`;
        d.confidence = Math.min(d.confidence, 0.4);
      }
    }
    return { costMicros: res.costMicros, wroteText, unsupportedClaims: wroteText ? res.data.unsupportedClaims.length : 0 };
  }
  const user = `Task: propose a 5–8 item section outline for a page answering this question.\nQuestion: ${d.llmDraft.prompt ?? ""}`;
  const res = await generateStructured({ schema: briefSchema, system, user, maxTokens: 500 });
  if (!res) return null;
  if (res.data.outline.length) {
    const outline = res.data.outline.slice(0, 8).map((s, i) => `${i + 1}. ${clip(s, 200)}`).join("\n");
    const flagged = res.data.unsupportedClaims.length ? `\n\n> AI flagged unsupported claims to verify: ${res.data.unsupportedClaims.slice(0, 5).join("; ")}` : "";
    d.proposedChange = { ...d.proposedChange, after: `${d.proposedChange.after}\n\n## AI-suggested outline (review)\n${outline}${flagged}` };
  }
  const wroteText = res.data.outline.length > 0;
  return { costMicros: res.costMicros, wroteText, unsupportedClaims: wroteText ? res.data.unsupportedClaims.length : 0 };
}

/**
 * Starting status for a new recommendation. Class A briefs / internal tasks (auto_execute, nothing is written to
 * the site) stay "proposed" with policyDecision auto_execute: they are ready to use but are NOT applied changes.
 * They only count as applied once someone marks them done (status "completed_manually").
 */
export function initialActionStatus(decision: string): "blocked" | "awaiting_approval" | "proposed" {
  return decision === "blocked" ? "blocked" : decision === "approval_required" ? "awaiting_approval" : "proposed";
}

export const analyzeJob: JobHandler = async (ctx) => {
  const orgId = ctx.run.organizationId;
  const projectId = ctx.run.projectId;
  if (!projectId) throw new JobError("analyze requires projectId", "permanent");
  const input = ctx.run.input as { trigger?: string; crawlRunId?: string; visibilityRunId?: string };
  const project = await db.project.findFirst({ where: { id: projectId, organizationId: orgId } });
  if (!project) throw new JobError("project_not_found", "permanent");
  const settings = (project.settings as (ProjectSettings & { businessFacts?: string[] }) | null) ?? {};
  const brands = (project.brandNames as string[] | null) ?? [];
  const facts: BusinessFacts = {
    name: project.name, brands, categories: (project.categories as string[] | null) ?? [],
    audience: project.audience, facts: Array.isArray(settings.businessFacts) ? settings.businessFacts.slice(0, 30) : [],
  };
  await ctx.transition("running", "analyze.started", { trigger: input.trigger ?? "manual" });

  // ---- Evidence: open findings + page extracts ----
  const findings = await db.auditFinding.findMany({
    where: { organizationId: orgId, projectId, status: "open" },
    orderBy: { detectedAt: "desc" },
    take: 500,
  });
  const pageIds = [...new Set(findings.map((f) => f.crawlPageId).filter((x): x is string => Boolean(x)))];
  const pages = pageIds.length
    ? await db.crawlPage.findMany({ where: { id: { in: pageIds }, organizationId: orgId }, select: { id: true, url: true, finalUrl: true, extracted: true } })
    : [];
  const pageById = new Map(pages.map((p) => {
    const x = (p.extracted as Partial<ExtractedPage> | null) ?? {};
    const ev: PageEvidence = { url: p.finalUrl ?? p.url, title: x.title ?? null, description: x.description ?? null, h1: x.h1 ?? [], textSample: x.textSample ?? "" };
    return [p.id, ev];
  }));
  const findingEvidence: FindingEvidence[] = findings.map((f) => ({
    id: f.id, code: f.code, severity: f.severity, category: f.category, message: f.message, pageUrl: f.pageUrl,
    evidence: (f.evidence as Record<string, unknown> | null) ?? {},
    page: f.crawlPageId ? pageById.get(f.crawlPageId) ?? null : null,
  }));

  // ---- Evidence: latest visibility run ----
  const vrun = input.visibilityRunId
    ? await db.visibilityRun.findFirst({ where: { id: input.visibilityRunId, organizationId: orgId, projectId } })
    : await db.visibilityRun.findFirst({
        where: { organizationId: orgId, projectId, status: { in: ["succeeded", "succeeded_with_warnings"] } },
        orderBy: { createdAt: "desc" },
      });
  let visibility: { runId: string; metrics: VisibilityMetrics | null; prompts: PromptEvidence[] } | null = null;
  if (vrun) {
    const obs = await db.observation.findMany({ where: { organizationId: orgId, visibilityRunId: vrun.id }, include: { prompt: true } });
    const byPrompt = new Map<string, PromptEvidence>();
    for (const o of obs) {
      let p = byPrompt.get(o.promptId);
      if (!p) {
        p = { id: o.promptId, text: o.prompt.text, intent: o.prompt.intent, priority: o.prompt.priority, observations: [] };
        byPrompt.set(o.promptId, p);
      }
      p.observations.push({
        brandMentioned: o.brandMentioned, brandCited: o.brandCited,
        competitorMentions: (o.competitorMentions as Record<string, number> | null) ?? {},
        citations: ((o.citations as { domain: string }[] | null) ?? []).filter((c) => c && typeof c.domain === "string"),
      });
    }
    visibility = { runId: vrun.id, metrics: (vrun.metrics as VisibilityMetrics | null) ?? null, prompts: [...byPrompt.values()] };
  }

  const drafts = buildRecommendations({ brand: brands[0] ?? project.name, findings: findingEvidence, visibility });
  await ctx.event("analyze.evidence_built", { findings: findings.length, visibilityRunId: vrun?.id ?? null, drafts: drafts.length });

  // ---- Integration + dedupe ----
  const integration = await db.integration.findFirst({
    where: { organizationId: orgId, projectId, provider: "wordpress", credentialEncrypted: { not: null }, health: { not: "failed" } },
    orderBy: { createdAt: "desc" },
  });
  const caps = integration ? capabilitiesOf(integration) : null;
  const open = await db.action.findMany({ where: { organizationId: orgId, projectId, status: { in: OPEN_STATUSES } }, select: { type: true, target: true } });
  const seen = new Set(open.map((a) => dedupeKey(a.type, a.target as ActionTarget | null)));

  let llmUsed = 0;
  const created: { id: string; type: string; riskClass: string; decision: string; status: string }[] = [];
  for (const d of drafts) {
    const key = dedupeKey(d.type, d.target);
    if (seen.has(key)) continue;
    seen.add(key);
    let llmWritten = false;
    let unsupportedClaims = 0;
    const deterministicText = d.proposedChange?.after;

    if (d.llmDraft && isLlmConfigured() && llmUsed < MAX_LLM_DRAFTS) {
      try {
        await reserveCredits(orgId, { provider: "openai", taskType: "content_generation", credits: 1, runId: ctx.run.id, projectId });
        llmUsed++;
        let r: LlmRefineResult | null = null;
        try {
          r = await llmRefine(d, facts);
        } finally {
          await releaseReservation(orgId, { provider: "openai", taskType: "content_generation", credits: 1, runId: ctx.run.id });
        }
        if (r) {
          llmWritten = r.wroteText;
          unsupportedClaims = r.unsupportedClaims;
        }
        if (r) await recordUsage(orgId, { provider: "openai", taskType: "content_generation", credits: 1, costMicros: r.costMicros, runId: ctx.run.id, projectId });
      } catch (e) {
        // Quota or provider failure: keep the deterministic draft.
        await ctx.event("analyze.llm_skipped", { reason: e instanceof Error ? e.message.slice(0, 200) : "error" });
      }
    }
    // Belt and braces: any change to the draft text during the LLM step counts as AI-written, even if a later
    // bookkeeping call (usage/reservation) failed before the result was recorded.
    if (d.proposedChange?.after !== deterministicText) llmWritten = true;
    const claims = detectRegulatedClaims(d.proposedChange?.after);
    if (claims.length && d.llmDraft) d.rationale += ` Contains claim-like wording (${claims.join(", ")}) — routed to manual review.`;

    const isWrite = WRITE_TYPES.has(d.type);
    const actionLike = { type: d.type, target: d.target as unknown as Prisma.JsonValue, proposedChange: d.proposedChange as unknown as Prisma.JsonValue };
    // Recommendation-time: with an integration use its capability snapshot; without one, classify only.
    const policy = enforceLlmReview(evaluatePolicy(actionLike, project, isWrite && caps ? caps : undefined), { llmWritten, unsupportedClaims });
    const { score, priority } = scorePriority(d.impact, d.confidence, d.effort, policy.riskClass);
    const hash = draftHash({ type: d.type, target: d.target, proposedChange: d.proposedChange, policyVersion: POLICY_VERSION });

    const status = initialActionStatus(policy.decision);

    const action = await db.action.create({
      data: {
        organizationId: orgId, projectId, type: d.type,
        target: d.target as unknown as Prisma.InputJsonValue,
        rationale: d.rationale,
        evidenceRefs: d.evidenceRefs as Prisma.InputJsonValue,
        priority, priorityScore: score, expectedImpact: d.expectedImpact, effort: d.effort, confidence: d.confidence,
        riskClass: policy.riskClass, policyDecision: policy.decision, policyReason: policy.reason, policyVersion: POLICY_VERSION,
        proposedChange: d.proposedChange ? (d.proposedChange as unknown as Prisma.InputJsonValue) : Prisma.JsonNull,
        draftHash: hash, status,
        integrationId: isWrite && integration ? integration.id : null,
      },
    });
    await ctx.event("recommendation.created", { actionId: action.id, type: d.type, riskClass: policy.riskClass, decision: policy.decision });

    if (status === "awaiting_approval") {
      await requestApproval(action.id, { organizationId: orgId, userId: null });
    } else if (policy.decision === "auto_execute" && policy.riskClass === "B" && !llmWritten && unsupportedClaims === 0) {
      try {
        await requestExecution(action.id, { organizationId: orgId, userId: null });
        await ctx.event("action.auto_execute_requested", { actionId: action.id });
      } catch (e) {
        await ctx.event("action.auto_execute_denied", { actionId: action.id, reason: e instanceof Error ? e.message : "denied" });
      }
    }
    created.push({ id: action.id, type: d.type, riskClass: policy.riskClass, decision: policy.decision, status });
  }

  const summary = {
    created: created.length,
    byDecision: created.reduce<Record<string, number>>((m, c) => ((m[c.decision] = (m[c.decision] ?? 0) + 1), m), {}),
    llmDrafts: llmUsed,
    visibilityRunId: vrun?.id ?? null,
    simulatedVisibility: Boolean(visibility?.metrics?.simulated),
  };
  await ctx.transition("succeeded", "analyze.completed", summary);
  return summary;
};
